import { readdirSync } from 'node:fs';
import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';

/**
 * Writes sw.js at build time with the full list of built files, so the installed app works offline from its first
 * visit. Requests to the save server (/api) always go to the network.
 */
function offlineServiceWorker(): Plugin {
  return {
    name: 'mds-offline-sw',
    apply: 'build',
    generateBundle(_opts, bundle) {
      const files = Object.keys(bundle).filter((f) => !f.endsWith('.map'));
      const pub = readdirSync(new URL('./public', import.meta.url)).filter((f) => !f.startsWith('.'));
      const precache = ['./', ...new Set([...files.filter((f) => f !== 'index.html'), ...pub])].map((f) => (f === './' ? f : `./${f}`));
      const version = files.filter((f) => f.startsWith('assets/')).sort().join('|');
      let h = 0;
      for (let i = 0; i < version.length; i++) h = (h * 31 + version.charCodeAt(i)) >>> 0;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: swSource(`mds-${h.toString(36)}`, precache) });
    },
  };
}

function swSource(cache: string, precache: string[]): string {
  return `// Generated by vite.config.ts: offline cache for the installed app.
const CACHE = ${JSON.stringify(cache)};
const PRECACHE = ${JSON.stringify(precache)};
const FONTS = 'mds-fonts';

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)));
});

self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) if (k !== CACHE && k !== FONTS) await caches.delete(k);
    await self.clients.claim();
  })());
});

// The page asks a waiting update to take over when the player chooses to reload.
self.addEventListener('message', (e) => { if (e.data === 'skip-waiting') self.skipWaiting(); });

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin === location.origin && url.pathname.includes('/api/')) return; // save server: always live
  if (url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com') {
    e.respondWith(caches.open(FONTS).then(async (c) => {
      const hit = await c.match(req);
      const net = fetch(req).then((r) => { c.put(req, r.clone()); return r; }).catch(() => hit);
      return hit ?? net;
    }));
    return;
  }
  if (url.origin !== location.origin) return;
  if (req.mode === 'navigate') {
    // Fresh page when online, the cached one when not.
    e.respondWith(fetch(req).then((r) => {
      const copy = r.clone();
      caches.open(CACHE).then((c) => c.put('./', copy));
      return r;
    }).catch(async () => (await caches.match('./')) ?? Response.error()));
    return;
  }
  e.respondWith(caches.match(req).then((hit) => hit ?? fetch(req).then((r) => {
    if (r.ok) { const copy = r.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
    return r;
  })));
});
`;
}

export default defineConfig({
  plugins: [react(), offlineServiceWorker()],
  build: {
    rollupOptions: {
      output: {
        // React changes rarely: its own chunk stays cached across releases.
        manualChunks: { react: ['react', 'react-dom'] },
      },
    },
  },
  server: {
    port: 5173,
    // The persistence API (npm run server) listens on 8787.
    proxy: { '/api': { target: `http://localhost:${process.env.API_PORT ?? 8787}`, changeOrigin: false } },
  },
});
